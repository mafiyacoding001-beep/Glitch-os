package com.example.data.model

import org.json.JSONArray
import org.json.JSONObject

data class GeneralSettings(
    val agentName: String = "AI Video Creator Pro",
    val mode: String = "autonomous",
    val modeOptions: List<String> = listOf("autonomous", "custom", "semi_autonomous"),
    val category: String = "Tech & Education",
    val categoryOptions: List<String> = listOf(
        "Tech & Education",
        "Business & News",
        "Entertainment",
        "Lifestyle & Vlogging",
        "Gaming",
        "Motivation & Storytelling"
    )
)

data class LanguageAndVoiceSettings(
    val language: String = "Hindi",
    val languageOptions: List<String> = listOf("Hindi", "English", "Hinglish", "Spanish"),
    val voiceGender: String = "male",
    val voiceGenderOptions: List<String> = listOf("male", "female"),
    val voiceAccent: String = "Indian Standard",
    val speechRate: Float = 1.0f,
    val pitch: String = "medium"
)

data class VideoFormatSettings(
    val orientation: String = "vertical",
    val orientationOptions: List<String> = listOf("horizontal", "vertical", "square"),
    val aspectRatio: String = "9:16",
    val resolution: String = "1080p",
    val fps: Int = 30,
    val maxDurationSeconds: Int = 60
)

data class CaptionsAndSubtitlesSettings(
    val captionsEnabled: Boolean = true,
    val captionStyle: String = "hormozi_bold",
    val fontFamily: String = "THE_BOLD_FONT",
    val fontSize: Int = 28,
    val textColor: String = "#FFFFFF",
    val highlightColor: String = "#FFE600",
    val strokeColor: String = "#000000",
    val strokeWidth: Float = 12f,
    val glowEffect: Boolean = true,
    val uppercase: Boolean = true,
    val wordsPerChunk: Int = 3,
    val position: String = "bottom",
    val showPillBackground: Boolean = false
)

data class SchedulingAndAutomationSettings(
    val autoGenerate: Boolean = true,
    val delayBetweenVideosSeconds: Int = 7200, // Default 2 hours
    val delayOptionsSeconds: List<Int> = listOf(30, 60, 120, 300, 600, 1800, 3600, 7200, 14400, 21600, 43200, 86400),
    val dailyVideoLimit: Int = 10, // Default 10 videos per day
    val postScheduleTimes: List<String> = listOf("09:00", "14:00", "18:00", "21:00")
)

data class ContentAndStyleSettings(
    val visualStyle: String = "realistic",
    val visualStyleOptions: List<String> = listOf("realistic", "anime", "cinematic", "3d_animation", "minimalist"),
    val visualRenderMode: String = "AI_IMAGES", // "AI_IMAGES", "HTML_CAPTION_ANIMATION"
    val visualRenderModeOptions: List<String> = listOf("AI_IMAGES", "HTML_CAPTION_ANIMATION"),
    val htmlTheme: String = "Cyberpunk Dark",
    val htmlThemeOptions: List<String> = listOf("Cyberpunk Dark", "Matrix Green", "OLED Minimal", "Neon Sunset"),
    val backgroundMusic: Boolean = true,
    val bgMusicVolume: Float = 0.2f,
    val voiceVolume: Float = 1.0f,
    val watermarkEnabled: Boolean = false
)

data class PublishingSettings(
    val autoPublish: Boolean = true,
    val platforms: List<String> = listOf("YouTube Shorts"),
    val autoGenerateTitle: Boolean = true,
    val autoGenerateDescription: Boolean = true,
    val autoGenerateHashtags: Boolean = true
)

data class GlitchAgentSettings(
    val general: GeneralSettings = GeneralSettings(),
    val languageAndVoice: LanguageAndVoiceSettings = LanguageAndVoiceSettings(),
    val videoFormat: VideoFormatSettings = VideoFormatSettings(),
    val captionsAndSubtitles: CaptionsAndSubtitlesSettings = CaptionsAndSubtitlesSettings(),
    val schedulingAndAutomation: SchedulingAndAutomationSettings = SchedulingAndAutomationSettings(),
    val contentAndStyle: ContentAndStyleSettings = ContentAndStyleSettings(),
    val publishing: PublishingSettings = PublishingSettings()
) {
    fun toJsonString(pretty: Boolean = true): String {
        val root = JSONObject()
        val settingsObj = JSONObject()

        // General
        val genObj = JSONObject()
        genObj.put("agent_name", general.agentName)
        genObj.put("mode", general.mode)
        genObj.put("mode_options", JSONArray(general.modeOptions))
        genObj.put("category", general.category)
        genObj.put("category_options", JSONArray(general.categoryOptions))
        settingsObj.put("general", genObj)

        // Language & Voice
        val langObj = JSONObject()
        langObj.put("language", languageAndVoice.language)
        langObj.put("language_options", JSONArray(languageAndVoice.languageOptions))
        langObj.put("voice_gender", languageAndVoice.voiceGender)
        langObj.put("voice_gender_options", JSONArray(languageAndVoice.voiceGenderOptions))
        langObj.put("voice_accent", languageAndVoice.voiceAccent)
        langObj.put("speech_rate", languageAndVoice.speechRate.toDouble())
        langObj.put("pitch", languageAndVoice.pitch)
        settingsObj.put("language_and_voice", langObj)

        // Video Format
        val vfObj = JSONObject()
        vfObj.put("orientation", videoFormat.orientation)
        vfObj.put("orientation_options", JSONArray(videoFormat.orientationOptions))
        vfObj.put("aspect_ratio", videoFormat.aspectRatio)
        vfObj.put("resolution", videoFormat.resolution)
        vfObj.put("fps", videoFormat.fps)
        vfObj.put("max_duration_seconds", videoFormat.maxDurationSeconds)
        settingsObj.put("video_format", vfObj)

        // Captions
        val capObj = JSONObject()
        capObj.put("captions_enabled", captionsAndSubtitles.captionsEnabled)
        capObj.put("caption_style", captionsAndSubtitles.captionStyle)
        capObj.put("font_family", captionsAndSubtitles.fontFamily)
        capObj.put("font_size", captionsAndSubtitles.fontSize)
        capObj.put("text_color", captionsAndSubtitles.textColor)
        capObj.put("highlight_color", captionsAndSubtitles.highlightColor)
        capObj.put("stroke_color", captionsAndSubtitles.strokeColor)
        capObj.put("stroke_width", captionsAndSubtitles.strokeWidth.toDouble())
        capObj.put("glow_effect", captionsAndSubtitles.glowEffect)
        capObj.put("uppercase", captionsAndSubtitles.uppercase)
        capObj.put("words_per_chunk", captionsAndSubtitles.wordsPerChunk)
        capObj.put("position", captionsAndSubtitles.position)
        capObj.put("show_pill_background", captionsAndSubtitles.showPillBackground)
        settingsObj.put("captions_and_subtitles", capObj)

        // Scheduling
        val schObj = JSONObject()
        schObj.put("auto_generate", schedulingAndAutomation.autoGenerate)
        schObj.put("delay_between_videos_seconds", schedulingAndAutomation.delayBetweenVideosSeconds)
        schObj.put("delay_options_seconds", JSONArray(schedulingAndAutomation.delayOptionsSeconds))
        schObj.put("daily_video_limit", schedulingAndAutomation.dailyVideoLimit)
        schObj.put("post_schedule_times", JSONArray(schedulingAndAutomation.postScheduleTimes))
        settingsObj.put("scheduling_and_automation", schObj)

        // Content & Style
        val csObj = JSONObject()
        csObj.put("visual_style", contentAndStyle.visualStyle)
        csObj.put("visual_style_options", JSONArray(contentAndStyle.visualStyleOptions))
        csObj.put("visual_render_mode", contentAndStyle.visualRenderMode)
        csObj.put("visual_render_mode_options", JSONArray(contentAndStyle.visualRenderModeOptions))
        csObj.put("html_theme", contentAndStyle.htmlTheme)
        csObj.put("html_theme_options", JSONArray(contentAndStyle.htmlThemeOptions))
        csObj.put("background_music", contentAndStyle.backgroundMusic)
        csObj.put("bg_music_volume", contentAndStyle.bgMusicVolume.toDouble())
        csObj.put("voice_volume", contentAndStyle.voiceVolume.toDouble())
        csObj.put("watermark_enabled", contentAndStyle.watermarkEnabled)
        settingsObj.put("content_and_style", csObj)

        // Publishing
        val pubObj = JSONObject()
        pubObj.put("auto_publish", publishing.autoPublish)
        pubObj.put("platforms", JSONArray(publishing.platforms))
        pubObj.put("auto_generate_title", publishing.autoGenerateTitle)
        pubObj.put("auto_generate_description", publishing.autoGenerateDescription)
        pubObj.put("auto_generate_hashtags", publishing.autoGenerateHashtags)
        settingsObj.put("publishing", pubObj)

        root.put("agent_settings", settingsObj)
        return if (pretty) root.toString(2) else root.toString()
    }

    fun toSystemPromptDirective(): String {
        return """
        >>> [ACTIVE GLITCH AGENT CONFIGURATION]
        - Agent Name: "${general.agentName}"
        - Mode: ${general.mode.uppercase()}
        - Content Category: ${general.category}
        - Language Target: ${languageAndVoice.language} (Accent: ${languageAndVoice.voiceAccent}, Voice: ${languageAndVoice.voiceGender.uppercase()})
        - Visual Art Style: ${contentAndStyle.visualStyle.uppercase()} (ensure all image prompts strictly follow ${contentAndStyle.visualStyle} styling)
        - Video Aspect Ratio: ${videoFormat.aspectRatio} (${videoFormat.orientation})
        - Target Duration: ~${videoFormat.maxDurationSeconds}s
        - Captions Style: ${if (captionsAndSubtitles.captionsEnabled) captionsAndSubtitles.captionStyle else "Disabled"} (Highlight: ${captionsAndSubtitles.highlightColor})
        - Publishing Targets: ${publishing.platforms.joinToString(", ")} (Auto-SEO: Title=${publishing.autoGenerateTitle}, Tags=${publishing.autoGenerateHashtags})
        """.trimIndent()
    }

    companion object {
        fun fromJsonString(jsonStr: String): GlitchAgentSettings {
            return try {
                val root = JSONObject(jsonStr)
                val settingsObj = root.optJSONObject("agent_settings") ?: root

                val genObj = settingsObj.optJSONObject("general")
                val general = if (genObj != null) {
                    val modeOpts = mutableListOf<String>()
                    genObj.optJSONArray("mode_options")?.let { arr ->
                        for (i in 0 until arr.length()) modeOpts.add(arr.getString(i))
                    }
                    val catOpts = mutableListOf<String>()
                    genObj.optJSONArray("category_options")?.let { arr ->
                        for (i in 0 until arr.length()) catOpts.add(arr.getString(i))
                    }
                    GeneralSettings(
                        agentName = genObj.optString("agent_name", "AI Video Creator Pro"),
                        mode = genObj.optString("mode", "autonomous"),
                        modeOptions = if (modeOpts.isNotEmpty()) modeOpts else GeneralSettings().modeOptions,
                        category = genObj.optString("category", "Tech & Education"),
                        categoryOptions = if (catOpts.isNotEmpty()) catOpts else GeneralSettings().categoryOptions
                    )
                } else GeneralSettings()

                val langObj = settingsObj.optJSONObject("language_and_voice")
                val languageAndVoice = if (langObj != null) {
                    val langOpts = mutableListOf<String>()
                    langObj.optJSONArray("language_options")?.let { arr ->
                        for (i in 0 until arr.length()) langOpts.add(arr.getString(i))
                    }
                    val voiceGenderOpts = mutableListOf<String>()
                    langObj.optJSONArray("voice_gender_options")?.let { arr ->
                        for (i in 0 until arr.length()) voiceGenderOpts.add(arr.getString(i))
                    }
                    LanguageAndVoiceSettings(
                        language = langObj.optString("language", "Hindi"),
                        languageOptions = if (langOpts.isNotEmpty()) langOpts else LanguageAndVoiceSettings().languageOptions,
                        voiceGender = langObj.optString("voice_gender", "male"),
                        voiceGenderOptions = if (voiceGenderOpts.isNotEmpty()) voiceGenderOpts else LanguageAndVoiceSettings().voiceGenderOptions,
                        voiceAccent = langObj.optString("voice_accent", "Indian Standard"),
                        speechRate = langObj.optDouble("speech_rate", 1.0).toFloat(),
                        pitch = langObj.optString("pitch", "medium")
                    )
                } else LanguageAndVoiceSettings()

                val vfObj = settingsObj.optJSONObject("video_format")
                val videoFormat = if (vfObj != null) {
                    val oriOpts = mutableListOf<String>()
                    vfObj.optJSONArray("orientation_options")?.let { arr ->
                        for (i in 0 until arr.length()) oriOpts.add(arr.getString(i))
                    }
                    VideoFormatSettings(
                        orientation = vfObj.optString("orientation", "vertical"),
                        orientationOptions = if (oriOpts.isNotEmpty()) oriOpts else VideoFormatSettings().orientationOptions,
                        aspectRatio = vfObj.optString("aspect_ratio", "9:16"),
                        resolution = vfObj.optString("resolution", "1080p"),
                        fps = vfObj.optInt("fps", 30),
                        maxDurationSeconds = vfObj.optInt("max_duration_seconds", 60)
                    )
                } else VideoFormatSettings()

                val capObj = settingsObj.optJSONObject("captions_and_subtitles")
                val captionsAndSubtitles = if (capObj != null) {
                    CaptionsAndSubtitlesSettings(
                        captionsEnabled = capObj.optBoolean("captions_enabled", true),
                        captionStyle = capObj.optString("caption_style", "hormozi_bold"),
                        fontFamily = capObj.optString("font_family", "THE_BOLD_FONT"),
                        fontSize = capObj.optInt("font_size", 28),
                        textColor = capObj.optString("text_color", "#FFFFFF"),
                        highlightColor = capObj.optString("highlight_color", "#FFE600"),
                        strokeColor = capObj.optString("stroke_color", "#000000"),
                        strokeWidth = capObj.optDouble("stroke_width", 12.0).toFloat(),
                        glowEffect = capObj.optBoolean("glow_effect", true),
                        uppercase = capObj.optBoolean("uppercase", true),
                        wordsPerChunk = capObj.optInt("words_per_chunk", 3),
                        position = capObj.optString("position", "bottom"),
                        showPillBackground = capObj.optBoolean("show_pill_background", false)
                    )
                } else CaptionsAndSubtitlesSettings()

                val schObj = settingsObj.optJSONObject("scheduling_and_automation")
                val schedulingAndAutomation = if (schObj != null) {
                    val delayOpts = mutableListOf<Int>()
                    val delayKey = if (schObj.has("delay_options_seconds")) "delay_options_seconds" else "delay_options_hours"
                    schObj.optJSONArray(delayKey)?.let { arr ->
                        for (i in 0 until arr.length()) delayOpts.add(arr.getInt(i))
                    }
                    val postTimes = mutableListOf<String>()
                    schObj.optJSONArray("post_schedule_times")?.let { arr ->
                        for (i in 0 until arr.length()) postTimes.add(arr.getString(i))
                    }
                    
                    val delayValue = if (schObj.has("delay_between_videos_seconds")) {
                        schObj.optInt("delay_between_videos_seconds", 120)
                    } else {
                        schObj.optInt("delay_between_videos_hours", 2) * 3600
                    }

                    SchedulingAndAutomationSettings(
                        autoGenerate = schObj.optBoolean("auto_generate", true),
                        delayBetweenVideosSeconds = delayValue,
                        delayOptionsSeconds = if (delayOpts.isNotEmpty()) {
                            if (delayKey == "delay_options_hours") delayOpts.map { it * 3600 } else delayOpts
                        } else SchedulingAndAutomationSettings().delayOptionsSeconds,
                        dailyVideoLimit = schObj.optInt("daily_video_limit", 10),
                        postScheduleTimes = if (postTimes.isNotEmpty()) postTimes else SchedulingAndAutomationSettings().postScheduleTimes
                    )
                } else SchedulingAndAutomationSettings()

                val csObj = settingsObj.optJSONObject("content_and_style")
                val contentAndStyle = if (csObj != null) {
                    val visOpts = mutableListOf<String>()
                    csObj.optJSONArray("visual_style_options")?.let { arr ->
                        for (i in 0 until arr.length()) visOpts.add(arr.getString(i))
                    }
                    val modeOpts = mutableListOf<String>()
                    csObj.optJSONArray("visual_render_mode_options")?.let { arr ->
                        for (i in 0 until arr.length()) modeOpts.add(arr.getString(i))
                    }
                    val thmOpts = mutableListOf<String>()
                    csObj.optJSONArray("html_theme_options")?.let { arr ->
                        for (i in 0 until arr.length()) thmOpts.add(arr.getString(i))
                    }
                    ContentAndStyleSettings(
                        visualStyle = csObj.optString("visual_style", "realistic"),
                        visualStyleOptions = if (visOpts.isNotEmpty()) visOpts else ContentAndStyleSettings().visualStyleOptions,
                        visualRenderMode = csObj.optString("visual_render_mode", "AI_IMAGES"),
                        visualRenderModeOptions = if (modeOpts.isNotEmpty()) modeOpts else ContentAndStyleSettings().visualRenderModeOptions,
                        htmlTheme = csObj.optString("html_theme", "Cyberpunk Dark"),
                        htmlThemeOptions = if (thmOpts.isNotEmpty()) thmOpts else ContentAndStyleSettings().htmlThemeOptions,
                        backgroundMusic = csObj.optBoolean("background_music", true),
                        bgMusicVolume = csObj.optDouble("bg_music_volume", 0.2).toFloat(),
                        voiceVolume = csObj.optDouble("voice_volume", 1.0).toFloat(),
                        watermarkEnabled = csObj.optBoolean("watermark_enabled", false)
                    )
                } else ContentAndStyleSettings()

                val pubObj = settingsObj.optJSONObject("publishing")
                val publishing = if (pubObj != null) {
                    val plats = mutableListOf<String>()
                    pubObj.optJSONArray("platforms")?.let { arr ->
                        for (i in 0 until arr.length()) plats.add(arr.getString(i))
                    }
                    PublishingSettings(
                        autoPublish = pubObj.optBoolean("auto_publish", true),
                        platforms = if (plats.isNotEmpty()) plats else PublishingSettings().platforms,
                        autoGenerateTitle = pubObj.optBoolean("auto_generate_title", true),
                        autoGenerateDescription = pubObj.optBoolean("auto_generate_description", true),
                        autoGenerateHashtags = pubObj.optBoolean("auto_generate_hashtags", true)
                    )
                } else PublishingSettings()

                GlitchAgentSettings(
                    general = general,
                    languageAndVoice = languageAndVoice,
                    videoFormat = videoFormat,
                    captionsAndSubtitles = captionsAndSubtitles,
                    schedulingAndAutomation = schedulingAndAutomation,
                    contentAndStyle = contentAndStyle,
                    publishing = publishing
                )
            } catch (e: Exception) {
                GlitchAgentSettings()
            }
        }
    }
}
